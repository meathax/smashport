"""Synthetic cache tests; actual translated behavior has separate native tests."""
import hashlib
import json
from pathlib import Path
import sys
import tempfile
import unittest
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'tools/gsp2cpp'))
from ensure_emission import ensure, MANIFEST

EMITTER = r'''
import argparse,json,sys
from pathlib import Path
p=argparse.ArgumentParser();p.add_argument('--out');p.add_argument('--codemap');p.add_argument('--chunk');a=p.parse_args()
root=Path(__file__).resolve().parents[2];out=Path(a.out);cfg=json.loads((root/'data/enhanced_fixture.json').read_text())
(out/'l8_chunk_000.cpp').write_text('// GENERATED by tools/gsp2cpp/emit.py\n'+cfg['body'])
if cfg.get('fail'):raise SystemExit(3)
(out/'l8_dispatch.cpp').write_text('// GENERATED by tools/gsp2cpp/emit.py\ndispatch')
(out/'enhanced_stage_balance.inc').write_text('fixture')
status='blocked' if cfg.get('blocked') else 'translated'
(out/'l8_translation_index.csv').write_text('address,instruction,source,chunk,status\nffe00000,MMTM B12,B1,B7,SP,TEST:1,chunk,'+status+'\n')
'''


class EmissionCacheTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)
        for name in ('tools/gsp2cpp', 'data', 'original/user-supplied-roms', 'generated/private'):
            (self.root/name).mkdir(parents=True)
        (self.root/'tools/gsp2cpp/emit.py').write_text(EMITTER)
        (self.root/'original/user-supplied-roms/smashtv.zip').write_bytes(b'synthetic cache input')
        (self.root/'generated/private/l8_codemap.json').write_text(json.dumps(dict(instructions={'ffe00000': []})))
        self.config = dict(body='first')
        self.configure()
        self.out = self.root/'generated/private/l8'

    def tearDown(self):
        self.temp.cleanup()

    def configure(self, **changes):
        self.config.update(changes)
        (self.root/'data/enhanced_fixture.json').write_text(json.dumps(self.config))

    def test_unsealed_cache_is_rejected_then_refresh_becomes_current(self):
        with self.assertRaisesRegex(RuntimeError, 'Stale or unsealed'):
            ensure(self.root)
        self.assertEqual(ensure(self.root, True)['result'], 'REFRESHED')
        before=(self.out/'l8_chunk_000.cpp').stat().st_mtime_ns
        self.assertEqual(ensure(self.root)['result'], 'CURRENT')
        self.assertEqual(ensure(self.root, True)['changed'], [])
        self.assertEqual((self.out/'l8_chunk_000.cpp').stat().st_mtime_ns, before)

    def test_input_change_refreshes_only_changed_outputs_and_archives_previous(self):
        ensure(self.root, True)
        old=(self.out/'l8_chunk_000.cpp').read_bytes()
        dispatch=(self.out/'l8_dispatch.cpp').stat().st_mtime_ns
        self.configure(body='second')
        with self.assertRaises(RuntimeError):ensure(self.root)
        self.assertEqual(ensure(self.root, True)['changed'], ['l8_chunk_000.cpp'])
        self.assertEqual((self.out/'l8_dispatch.cpp').stat().st_mtime_ns, dispatch)
        backup=self.root/'build/l8-emission-history'/hashlib.sha256(old).hexdigest()/'l8_chunk_000.cpp'
        self.assertEqual(backup.read_bytes(), old)

    def test_nonfunctional_input_change_preserves_all_cpp_mtimes(self):
        ensure(self.root, True)
        before={p.name:p.stat().st_mtime_ns for p in self.out.glob('*.cpp')}
        self.configure(note='no emitted change')
        self.assertEqual(ensure(self.root, True)['changed'], [])
        self.assertEqual({p.name:p.stat().st_mtime_ns for p in self.out.glob('*.cpp')}, before)

    def test_output_tamper_is_rejected_and_preserved_on_refresh(self):
        ensure(self.root, True)
        target=self.out/'l8_chunk_000.cpp';target.write_text('private local alteration')
        altered=target.read_bytes()
        with self.assertRaises(RuntimeError):ensure(self.root)
        ensure(self.root, True)
        backup=self.root/'build/l8-emission-history'/hashlib.sha256(altered).hexdigest()/target.name
        self.assertEqual(backup.read_bytes(), altered)

    def test_failed_or_blocked_generation_keeps_published_sources_and_manifest(self):
        ensure(self.root, True)
        before={p.name:p.read_bytes() for p in self.out.iterdir() if p.name!='.emission.lock'}
        for config in ({'fail':True}, {'fail':False,'blocked':True}):
            self.configure(**config)
            with self.assertRaises(RuntimeError):ensure(self.root, True)
            self.assertEqual({p.name:p.read_bytes() for p in self.out.iterdir() if p.name!='.emission.lock'}, before)

    def test_unknown_private_sources_are_not_removed(self):
        ensure(self.root, True)
        foreign=self.out/'l8_custom.cpp';foreign.write_text('unowned private work')
        with self.assertRaisesRegex(RuntimeError, 'unowned private source'):
            ensure(self.root, True)
        self.assertEqual(foreign.read_text(), 'unowned private work')

    def test_empty_forged_manifest_does_not_authorize_missing_outputs(self):
        ensure(self.root, True)
        path=self.out/MANIFEST;manifest=json.loads(path.read_text())
        for name in manifest['outputs']:(self.out/name).unlink()
        manifest['outputs']={};path.write_text(json.dumps(manifest))
        with self.assertRaises(RuntimeError):ensure(self.root)


if __name__ == '__main__':
    unittest.main()
